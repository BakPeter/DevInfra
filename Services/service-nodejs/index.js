const express = require('express');
const { Kafka, logLevel } = require('kafkajs');
const { Pool } = require('pg');
const winston = require('winston');
const { SeqTransport } = require('@datalust/winston-seq');

const seqServerUrl = process.env.SEQ_SERVER_URL || 'http://localhost:5341';

const logger = winston.createLogger({
  level: 'info',
  format: winston.format.combine(winston.format.errors({ stack: true }), winston.format.json()),
  defaultMeta: { service: 'service-nodejs' },
  transports: [
    new winston.transports.Console({
      format: winston.format.simple(),
    }),
    new SeqTransport({
      serverUrl: seqServerUrl,
      //   apiKey: seqApiKey,
      onError: (error) => {
        console.error('Seq logging failed', error);
      },
      handleExceptions: true,
      handleRejections: true,
    }),
  ],
});

const app = express();
const port = Number(process.env.NODEJS_SERVICE_REST_PORT || process.env.PORT) || 3000;
const kafkaBrokers = (process.env.KAFKA_BOOTSTRAP_SERVERS || 'localhost:9092')
  .split(',')
  .map((broker) => broker.trim())
  .filter(Boolean);
const kafkaTopic = process.env.KAFKA_TOPIC_ITEMS_NODEJS_SERVICE || 'items.events';
const kafkaStateTopic = process.env.KAFKA_TOPIC_STATE_NODEJS_SERVICE || 'service-nodejs.state';
const stateIntervalMs =
  (Number(process.env.NODEJS_SERVICE_STATE_INTERVAL_SECONDS) || 30) * 1000;
const stateProbeTimeoutMs = 3000;
const stateSinkTimeoutMs = 5000;
const kafkaConsumerTopics = process.env.NODEJS_SERVICE_KAFKA_CONSUMER_TOPICS.split(',')
  .map((topic) => topic.trim())
  .filter(Boolean);
logger.info('Kafka Topic {topic}', {
  topic: kafkaTopic,
  KAFKA_TOPIC_ITEMS_NODEJS_SERVICE: process.env.KAFKA_TOPIC_ITEMS_NODEJS_SERVICE,
  KAFKA_TOPIC_ITEMS: process.env.KAFKA_TOPIC_ITEMS,
  NODEJS_SERVICE_KAFKA_CONSUMER_TOPICS: kafkaConsumerTopics,
  action: 'initialized',
});
// const seqApiKey = process.env.SEQ_API_KEY;

const postgresSchema = process.env.POSTGRES_SCHEMA || 'nodejs';

// A schema name cannot be a bound parameter, so it is interpolated and must be validated.
if (!/^[a-z_][a-z0-9_]*$/.test(postgresSchema)) {
  throw new Error(`Invalid POSTGRES_SCHEMA: ${postgresSchema}`);
}

const itemsTable = `${postgresSchema}.items`;
const serviceStateTable = `${postgresSchema}.service_state`;
const pool = new Pool({
  host: process.env.POSTGRES_HOST || 'localhost',
  port: Number(process.env.POSTGRES_PORT) || 5432,
  user: process.env.POSTGRES_USER || 'postgres',
  password: process.env.POSTGRES_PASSWORD || 'postgres',
  database: process.env.POSTGRES_DB || 'devinfra',
});

const kafka = new Kafka({
  clientId: 'service-nodejs',
  brokers: kafkaBrokers,
});

// Separate client for the health probe: the shared producer caches its connection and
// reports a dead broker as reachable, and its default retry policy takes ~30s to give
// up, which would stall the state tick. This one fails fast and stays quiet.
const kafkaProbe = new Kafka({
  clientId: 'service-nodejs-probe',
  brokers: kafkaBrokers,
  connectionTimeout: 2000,
  requestTimeout: 2000,
  retry: { retries: 0 },
  logLevel: logLevel.NOTHING,
});
const producer = kafka.producer();
const consumer = kafka.consumer({
  groupId: process.env.KAFKA_CONSUMER_GROUP_ID || 'service-nodejs-consumer',
});
let producerConnectPromise;
let consumerConnectPromise;

function getProducer() {
  if (!producerConnectPromise) {
    producerConnectPromise = producer.connect().then(() => producer);
  }

  return producerConnectPromise;
}

async function initDb() {
  await pool.query(`CREATE SCHEMA IF NOT EXISTS ${postgresSchema}`);
  await pool.query(
    `CREATE TABLE IF NOT EXISTS ${itemsTable} (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name text NOT NULL
    )`,
  );
  await pool.query(
    `INSERT INTO ${itemsTable} (name)
     SELECT unnest(ARRAY['alpha', 'beta', 'gamma'])
     WHERE NOT EXISTS (SELECT 1 FROM ${itemsTable})`,
  );
  await pool.query(
    `CREATE TABLE IF NOT EXISTS ${serviceStateTable} (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      published_at timestamptz NOT NULL,
      origin_service text NOT NULL,
      health_state text NOT NULL,
      checks jsonb NOT NULL
    )`,
  );
  await pool.query(
    `CREATE INDEX IF NOT EXISTS service_state_published_at_idx
     ON ${serviceStateTable} (published_at DESC)`,
  );

  logger.info('Postgres schema ready {schema}', {
    schema: postgresSchema,
    database: process.env.POSTGRES_DB || 'devinfra',
    action: 'db_initialized',
  });
}

async function startConsumer() {
  if (kafkaConsumerTopics.length === 0) {
    logger.info('Kafka consumer disabled because no topics were configured');
    return null;
  }

  if (!consumerConnectPromise) {
    consumerConnectPromise = (async () => {
      await consumer.connect();

      for (const topic of kafkaConsumerTopics) {
        await consumer.subscribe({ topic, fromBeginning: false });
      }

      await consumer.run({
        eachMessage: async ({ topic, partition, message }) => {
          logger.info('Consumed Kafka event from {topic}', {
            topic,
            partition,
            key: message.key?.toString(),
            value: message.value?.toString(),
            headers: Object.fromEntries(
              Object.entries(message.headers || {}).map(([header, value]) => [
                header,
                value?.toString(),
              ]),
            ),
          });
        },
      });

      logger.info('Kafka consumer subscribed to topics', {
        topics: kafkaConsumerTopics,
        groupId: process.env.KAFKA_CONSUMER_GROUP_ID || 'service-nodejs-consumer',
      });

      return consumer;
    })().catch((error) => {
      consumerConnectPromise = undefined;
      logger.error('Failed to start Kafka consumer', {
        topics: kafkaConsumerTopics,
        groupId: process.env.KAFKA_CONSUMER_GROUP_ID || 'service-nodejs-consumer',
        error,
      });
      throw error;
    });
  }

  return consumerConnectPromise;
}

async function publishItemEvent(action, item) {
  try {
    const connectedProducer = await getProducer();
    await connectedProducer.send({
      topic: kafkaTopic,
      messages: [
        {
          key: String(item.id),
          value: JSON.stringify({
            action,
            item,
            occurredAt: new Date().toISOString(),
          }),
        },
      ],
    });

    logger.info('Published Kafka event {action} for item {itemId}', {
      action,
      itemId: item.id,
      topic: kafkaTopic,
    });
  } catch (error) {
    logger.error('Failed to publish Kafka event {action} for item {itemId}', {
      action,
      itemId: item.id,
      topic: kafkaTopic,
      error,
    });
  }
}

function withTimeout(promise, timeoutMs, label) {
  // The underlying promise keeps running after a timeout, so swallow its late rejection
  // to avoid an unhandled rejection once this race has already reported the failure.
  promise.catch(() => {});

  return Promise.race([
    promise,
    new Promise((_resolve, reject) => {
      setTimeout(() => reject(new Error(`${label} timed out after ${timeoutMs} ms`)), timeoutMs).unref();
    }),
  ]);
}

async function probePostgres() {
  try {
    await withTimeout(pool.query('SELECT 1'), stateProbeTimeoutMs, 'Postgres probe');
    return 'Healthy';
  } catch (error) {
    logger.error('Postgres health probe failed', { error });
    return 'Unhealthy';
  }
}

// A real metadata round-trip: anything cached would report a stopped broker as reachable.
async function probeKafka() {
  const admin = kafkaProbe.admin();

  try {
    await withTimeout(
      admin.connect().then(() => admin.listTopics()),
      stateProbeTimeoutMs,
      'Kafka probe',
    );
    return 'Healthy';
  } catch (error) {
    logger.error('Kafka health probe failed', { error: error.message });
    return 'Unhealthy';
  } finally {
    admin.disconnect().catch(() => {});
  }
}

async function writeStateToKafka(serviceState) {
  try {
    const connectedProducer = await withTimeout(
      getProducer(),
      stateSinkTimeoutMs,
      'Kafka producer connect',
    );

    await withTimeout(
      connectedProducer.send({
        topic: kafkaStateTopic,
        messages: [
          {
            key: 'ServiceState',
            value: JSON.stringify(serviceState),
          },
        ],
      }),
      stateSinkTimeoutMs,
      'Kafka publish',
    );
  } catch (error) {
    // Drop the cached connect promise so the next tick retries from scratch.
    producerConnectPromise = undefined;
    logger.error('Failed to publish service state to Kafka', {
      topic: kafkaStateTopic,
      error: error.message,
    });
  }
}

function writeStateToSeq(serviceState) {
  try {
    logger.info('Service state {healthState} for {originService}', {
      ...serviceState,
      topic: kafkaStateTopic,
      action: 'service_state',
    });
  } catch (error) {
    console.error('Failed to log service state', error);
  }
}

async function writeStateToPostgres(serviceState) {
  try {
    await withTimeout(
      pool.query(
        `INSERT INTO ${serviceStateTable} (published_at, origin_service, health_state, checks)
         VALUES ($1, $2, $3, $4)`,
        [
          serviceState.publishedAt,
          serviceState.originService,
          serviceState.healthState,
          JSON.stringify(serviceState.checks),
        ],
      ),
      stateSinkTimeoutMs,
      'Postgres insert',
    );
  } catch (error) {
    logger.error('Failed to store service state in Postgres', {
      table: serviceStateTable,
      error: error.message,
    });
  }
}

// The three sinks run concurrently and each owns its own error handling, so a dead
// Kafka can neither fail nor delay the Seq and Postgres writes.
async function publishServiceState() {
  const [postgres, kafkaCheck] = await Promise.all([probePostgres(), probeKafka()]);
  const checks = { postgres, kafka: kafkaCheck };
  const results = Object.values(checks);
  const unhealthy = results.filter((result) => result !== 'Healthy').length;

  const serviceState = {
    publishedAt: new Date().toISOString(),
    originService: 'service-nodejs',
    healthState:
      unhealthy === 0 ? 'Healthy' : unhealthy === results.length ? 'Unhealthy' : 'Degraded',
    checks,
  };

  await Promise.allSettled([
    writeStateToKafka(serviceState),
    writeStateToSeq(serviceState),
    writeStateToPostgres(serviceState),
  ]);
}

app.use(express.json());
app.use((request, response, next) => {
  const startedAt = Date.now();

  response.on('finish', () => {
    logger.info('HTTP {method} {path} responded {statusCode} in {durationMs} ms', {
      method: request.method,
      path: request.originalUrl,
      statusCode: response.statusCode,
      durationMs: Date.now() - startedAt,
      ip: request.ip,
      userAgent: request.get('user-agent'),
    });
  });

  next();
});

app.get('/health', (_request, response) => {
  response.json({ status: 'ok' });
});

app.get('/api/items', async (_request, response) => {
  const { rows: items } = await pool.query(`SELECT id, name FROM ${itemsTable} ORDER BY id`);

  for (const item of items) {
    await publishItemEvent('fetched', item);
  }

  response.json(items);
});

app.get('/api/items/:id', async (request, response) => {
  const itemId = Number(request.params.id);
  const { rows } = await pool.query(`SELECT id, name FROM ${itemsTable} WHERE id = $1`, [itemId]);

  if (rows.length === 0) {
    response.status(404).json({ message: 'Item not found' });
    return;
  }

  response.json(rows[0]);
});

app.post('/api/items', async (request, response) => {
  const { name } = request.body;

  if (typeof name !== 'string' || name.trim() === '') {
    response.status(400).json({ message: 'name is required' });
    return;
  }

  const { rows } = await pool.query(
    `INSERT INTO ${itemsTable} (name) VALUES ($1) RETURNING id, name`,
    [name.trim()],
  );
  const item = rows[0];

  await publishItemEvent('created', item);

  response.status(201).json(item);
});

app.put('/api/items/:id', async (request, response) => {
  const itemId = Number(request.params.id);
  const { rows: existing } = await pool.query(`SELECT id FROM ${itemsTable} WHERE id = $1`, [
    itemId,
  ]);
  const { name } = request.body;

  if (existing.length === 0) {
    response.status(404).json({ message: 'Item not found' });
    return;
  }

  if (typeof name !== 'string' || name.trim() === '') {
    response.status(400).json({ message: 'name is required' });
    return;
  }

  const { rows } = await pool.query(
    `UPDATE ${itemsTable} SET name = $1 WHERE id = $2 RETURNING id, name`,
    [name.trim(), itemId],
  );
  const item = rows[0];

  await publishItemEvent('updated', item);
  response.json(item);
});

app.delete('/api/items/:id', async (request, response) => {
  const itemId = Number(request.params.id);
  const { rows } = await pool.query(`DELETE FROM ${itemsTable} WHERE id = $1 RETURNING id, name`, [
    itemId,
  ]);

  if (rows.length === 0) {
    response.status(404).json({ message: 'Item not found' });
    return;
  }

  await publishItemEvent('deleted', rows[0]);

  response.status(204).send();
});

let stateIntervalHandle;

if (require.main === module) {
  initDb()
    .then(() => {
      app.listen(port, () => {
        logger.info('REST API listening on port {port}', { port });
      });

      stateIntervalHandle = setInterval(publishServiceState, stateIntervalMs);
      logger.info('Service state publisher started every {intervalMs} ms', {
        intervalMs: stateIntervalMs,
        topic: kafkaStateTopic,
      });

      return startConsumer();
    })
    .catch((error) => {
      logger.error('Failed to start service', { error });
      process.exitCode = 1;
    });
}

async function shutdown() {
  if (stateIntervalHandle) {
    clearInterval(stateIntervalHandle);
  }

  try {
    if (consumerConnectPromise) {
      await consumer.disconnect();
    }
  } catch (error) {
    logger.error('Failed to disconnect Kafka consumer', { error });
  }

  try {
    if (producerConnectPromise) {
      await producer.disconnect();
    }
  } catch (error) {
    logger.error('Failed to disconnect Kafka producer', { error });
  }

  try {
    await pool.end();
  } catch (error) {
    logger.error('Failed to close Postgres pool', { error });
  }
}

process.on('SIGINT', () => {
  shutdown().finally(() => process.exit(0));
});

process.on('SIGTERM', () => {
  shutdown().finally(() => process.exit(0));
});

module.exports = app;
